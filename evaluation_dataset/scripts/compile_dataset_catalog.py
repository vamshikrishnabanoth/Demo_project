#!/usr/bin/env python3
"""
scripts/compile_dataset_catalog.py

Compiles all individual item metadata.json files into:
1. dataset_catalog.json (master machine-readable database)
2. DATASET_CATALOG.md (human-readable catalog table)
"""

import os
import sys
import json
import glob

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CATALOG_JSON = os.path.join(BASE_DIR, "dataset_catalog.json")
CATALOG_MD = os.path.join(BASE_DIR, "DATASET_CATALOG.md")

def compile_catalog():
    print("=" * 85)
    print("📖 COMPILING MASTER EVALUATION DATASET CATALOG")
    print("=" * 85)

    meta_files = sorted(glob.glob(os.path.join(BASE_DIR, "0*", "*", "metadata.json")))
    items = []

    for m_path in meta_files:
        try:
            with open(m_path, "r", encoding="utf-8") as f:
                data = json.load(f)
                items.append(data)
        except Exception as e:
            print(f"⚠️ Error reading {m_path}: {e}")

    # Sort items by modality and dataset_id
    items.sort(key=lambda x: (x.get("modality", ""), x.get("dataset_id", "")))

    # 1. Write dataset_catalog.json
    catalog_obj = {
        "dataset_name": "Lecture-to-MCQ Evaluation Benchmark Population",
        "total_items": len(items),
        "modality_breakdown": {
            "VOICE_ONLY": len([i for i in items if i.get("modality") == "VOICE_ONLY"]),
            "VOICE_PLUS_MATERIAL": len([i for i in items if i.get("modality") == "VOICE_PLUS_MATERIAL"]),
            "MATERIAL_ONLY": len([i for i in items if i.get("modality") == "MATERIAL_ONLY"]),
            "EDGE_CASES": len([i for i in items if i.get("modality") == "EDGE_CASES"])
        },
        "items": items
    }

    with open(CATALOG_JSON, "w", encoding="utf-8") as jf:
        json.dump(catalog_obj, jf, indent=2)
    print(f"  -> Generated JSON Catalog: {CATALOG_JSON} ({len(items)} items)")

    # 2. Write DATASET_CATALOG.md
    md_lines = [
        "# Master Evaluation Dataset Catalog",
        "",
        f"**Total Registered Evaluation Items**: {len(items)}",
        "",
        "### Modality Breakdown",
        f"- **VOICE_ONLY**: {catalog_obj['modality_breakdown']['VOICE_ONLY']}",
        f"- **VOICE_PLUS_MATERIAL**: {catalog_obj['modality_breakdown']['VOICE_PLUS_MATERIAL']}",
        f"- **MATERIAL_ONLY**: {catalog_obj['modality_breakdown']['MATERIAL_ONLY']}",
        f"- **EDGE_CASES**: {catalog_obj['modality_breakdown']['EDGE_CASES']}",
        "",
        "---",
        "",
        "### Item Registry",
        "",
        "| ID | Modality | Subject | Topic | Duration | Expected Gate | Behavior | Contributor |",
        "| :--- | :--- | :--- | :--- | :--- | :---: | :--- | :---: |"
    ]

    if not items:
        md_lines.append("| *None* | *Waiting for teammate ZIPs* | — | — | — | — | — | — |")
    else:
        for i in items:
            d_id = i.get("dataset_id", "UNKNOWN")
            mod = i.get("modality", "UNKNOWN")
            subj = i.get("subject", "UNKNOWN")
            top = i.get("topic", "Untitled")
            dur = i.get("duration", "TBD")
            acad = i.get("expected_academicity", "TBD")
            beh = i.get("expected_content_behavior", "TBD")
            contrib = i.get("contributor", "TBD")
            md_lines.append(f"| `{d_id}` | {mod} | {subj} | {top} | {dur} | {acad} | `{beh}` | {contrib} |")

    md_lines.append("")
    md_lines.append("---")
    md_lines.append("*Generated by compile_dataset_catalog.py*")

    with open(CATALOG_MD, "w", encoding="utf-8") as mf:
        mf.write("\\n".join(md_lines))
    print(f"  -> Generated Markdown Catalog: {CATALOG_MD}")
    print("=" * 85)

if __name__ == "__main__":
    compile_catalog()
